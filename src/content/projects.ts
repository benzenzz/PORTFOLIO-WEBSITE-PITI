import media from "./media.json"; // generated by scripts/import-media.mjs

// Real data comes from content-raw/ and the owner's answers. Anything not yet supplied stays a short
// bracketed keyword saying what goes there — never fill these with invented facts.
export type Media = { src: string; width?: number; height?: number; video?: boolean };

/** Where the work lived. "playground" shows on /playground only; "hidden" is kept but not published. */
export type Group = "event" | "social" | "playground" | "hidden";

/** Case-study depth: A flagship (full story), B project (context + videos), C snapshot (one piece). */
export type Tier = "A" | "B" | "C";

export type Project = {
  title: string;
  slug: string;
  group: Group;
  tier: Tier;
  /** Medium tags, shown on the index and project page. */
  tags: string[];
  year: string;
  /** One line under the title: what it was, for whom. */
  summary: string;
  /** Public path of a still (cover or poster frame). */
  cover: string | null;
  /** Short muted loop for the homepage tile. */
  preview?: string;
  glance: { client: string; role: string; team: string; format: string; tools: string };
  brief: string;
  decisions: string[];
  process: string;
  result: string;
  learned: string;
  media: Media[];
  /** YouTube video ids, embedded behind a click-to-play facade. */
  youtube?: string[];
};

